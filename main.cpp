#include <string>
#include <vector>

void sum_squares() {
    int acc = 0;
    for (int i = -5; i <= 5; ++i) acc += i * i;
    (void)acc;
}

void integer_power() {
    int base = 2, exp = 8;
    int power = 1;
    for (int i = 0; i < exp; ++i) power *= base;
    (void)power;
}

void collect_triples() {
    std::vector<int> values;
    for (int i = 1; i <= 5; ++i) values.push_back(i * 3);
    int total = 0;
    for (std::size_t i = 0; i < values.size(); ++i) total += values[i];
    (void)total;
}

void count_multiples() {
    int count = 0;
    for (int i = 1; i <= 100; ++i) {
        if (i % 7 == 0) count += 1;
    }
    (void)count;
}

extern "C" int subtle_beacon();
extern "C" void misty_maple();
extern "C" void still_hollow();
extern "C" void bright_ember();

int main() {
    sum_squares();
    integer_power();
    collect_triples();
    count_multiples();
    misty_maple();
    still_hollow();
    bright_ember();
    return subtle_beacon();
}
